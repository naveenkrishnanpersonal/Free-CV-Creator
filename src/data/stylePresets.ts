import type { SectionKind } from '@/lib/constants'
import type { StyleConfig } from '@/lib/schema'
import { DEFAULT_STYLE } from './defaults'

type PresetCategory = 'Single column' | 'Sidebar' | 'Header band'

type Overrides = {
  layout?: StyleConfig['layout']
  sidebarWidthPct?: number
  sidebarSections?: SectionKind[]
  columnGapMm?: number
  typography?: Partial<StyleConfig['typography']>
  colors?: Partial<StyleConfig['colors']>
  header?: Partial<StyleConfig['header']>
  section?: Partial<StyleConfig['section']>
  entry?: Partial<StyleConfig['entry']>
  page?: Partial<StyleConfig['page']>
  sectionVariants?: StyleConfig['sectionVariants']
}

export type StylePreset = {
  id: string
  name: string
  tagline: string
  category: PresetCategory
  atsSafe?: boolean
  style: StyleConfig
}

function preset(
  id: string,
  name: string,
  tagline: string,
  category: PresetCategory,
  overrides: Overrides,
  atsSafe = false,
): StylePreset {
  const base = structuredClone(DEFAULT_STYLE)
  const { typography, colors, header, section, entry, page, sectionVariants, ...top } = overrides
  return {
    id,
    name,
    tagline,
    category,
    atsSafe,
    style: {
      ...base,
      ...top,
      version: 1,
      name,
      basePreset: id,
      typography: { ...base.typography, ...typography },
      colors: { ...base.colors, ...colors },
      header: { ...base.header, ...header },
      section: { ...base.section, ...section },
      entry: { ...base.entry, ...entry },
      page: { ...base.page, ...page },
      sectionVariants: sectionVariants ?? {},
      customCss: '',
      layoutBuilder: null,
    },
  }
}

